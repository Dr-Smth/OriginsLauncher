#!/usr/bin/env python3
"""Reproduce the small original-source Wine helper; never touches a runtime.

Apple clang assembles a relocatable Mach-O object. We accept one text section,
no unresolved relocations, and resolve exactly two module-relative references.
The generated Python bytes travel with source so end users need no compiler.
"""
import argparse
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
STUB_OFFSET = 0x7fb00
PATCH_OFFSET = 0x64d9b
ORIGINAL_SHA256 = 'f51a982887a7408af33abe573b296ad5eaf0a1337c2aeeae84e5ea6605496bf3'

def build():
    source = ROOT / 'source/native/laa_gate.S'
    with tempfile.TemporaryDirectory(prefix='origins-laa-build-') as tmp:
        obj = Path(tmp) / 'gate.o'
        subprocess.run(['/usr/bin/clang','-arch','x86_64','-c',str(source),'-o',str(obj)],check=True)
        raw = obj.read_bytes()
    assert struct.unpack_from('<II',raw) == (0xfeedfacf,0x01000007)
    ncmds = struct.unpack_from('<I',raw,16)[0]
    pos = 32
    code = None
    for _ in range(ncmds):
        cmd,size = struct.unpack_from('<II',raw,pos)
        if cmd == 0x19:
            count = struct.unpack_from('<I',raw,pos+64)[0]
            for i in range(count):
                sec = pos+72+80*i
                name,segment,addr,length,offset,align,reloff,nrel = struct.unpack_from('<16s16sQQIIII',raw,sec)
                if name.rstrip(b'\0') == b'__text':
                    assert code is None and nrel == 0, 'Unexpected external relocation'
                    code = bytearray(raw[offset:offset+length])
        pos += size
    assert code and len(code) < 0x500
    for marker,target,tail in ((b'\x66\x81\x3d'+b'\x22'*4+b'\x4c\x01',0xae310,2),
                               (b'\x48\x8b\x05'+b'\x11'*4,0xae210,0)):
        assert code.count(marker)==1, 'Missing or ambiguous native-global marker'
        start = code.index(marker)
        displacement = target-(STUB_OFFSET+start+len(marker))
        struct.pack_into('<i',code,start+3,displacement)
    call = b'\xe8'+struct.pack('<i',STUB_OFFSET-(PATCH_OFFSET+5))+b'\x90'*4
    text = ('# Generated by scripts/build_laa_stub.py; do not hand-edit.\n'
            '# SPDX-License-Identifier: GPL-3.0-only\n'
            '# Source: native/laa_gate.S. Only the exact pinned native Wine module is supported.\n'
            f'STUB_VERSION = 1\nORIGINAL_SHA256 = {ORIGINAL_SHA256!r}\n'
            f'PATCH_OFFSET = {PATCH_OFFSET:#x}\n'
            "ORIGINAL_BYTES = bytes.fromhex('c1e01a480dffffff7f')\n"
            f'PATCH_BYTES = bytes.fromhex({call.hex()!r})\n'
            f'STUB_OFFSET = {STUB_OFFSET:#x}\n'
            f'STUB_SHA256 = {hashlib.sha256(code).hexdigest()!r}\n'
            f'SOURCE_SHA256 = {hashlib.sha256(source.read_bytes()).hexdigest()!r}\n'
            'STUB_CODE = bytes.fromhex(\n')
    for i in range(0,len(code),32):
        text += f'    {code[i:i+32].hex()!r}\n'
    text += ')\n'
    return text

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    target=ROOT/'source/laa_stub.py'
    text=build()
    if args.check:
        if target.read_text()!=text:
            raise SystemExit('Generated helper differs from assembly source; regenerate before building.')
        print('Generated Wine helper matches its assembly source.')
    else:
        target.write_text(text)
        print(target)

if __name__=='__main__':
    main()
